pub const N: usize = 65;

pub struct Lang {
    pub code: &'static str,
    pub name: &'static str,
    pub words: &'static [&'static str; N],
}

pub fn tr(lang: usize, k: K) -> &'static str {
    let lang = lang.min(LANGS.len() - 1);
    let i = k as usize;
    if i < N {
        LANGS[lang].words[i]
    } else if i < N + crate::i18n_extra::N2 {
        crate::i18n_extra::EXTRA[lang][i - N]
    } else if i < N + crate::i18n_extra::N2 + crate::i18n_extra2::N3 {
        crate::i18n_extra2::EXTRA2[lang][i - N - crate::i18n_extra::N2]
    } else if i < N + crate::i18n_extra::N2 + crate::i18n_extra2::N3 + crate::i18n_extra3::N4 {
        crate::i18n_extra3::EXTRA3[lang][i - N - crate::i18n_extra::N2 - crate::i18n_extra2::N3]
    } else if i < N + crate::i18n_extra::N2 + crate::i18n_extra2::N3 + crate::i18n_extra3::N4 + crate::i18n_extra4::N5 {
        crate::i18n_extra4::EXTRA4[lang][i - N - crate::i18n_extra::N2 - crate::i18n_extra2::N3 - crate::i18n_extra3::N4]
    } else if i < N + crate::i18n_extra::N2 + crate::i18n_extra2::N3 + crate::i18n_extra3::N4 + crate::i18n_extra4::N5 + crate::i18n_extra5::N6 {
        crate::i18n_extra5::EXTRA5[lang]
            [i - N - crate::i18n_extra::N2 - crate::i18n_extra2::N3 - crate::i18n_extra3::N4 - crate::i18n_extra4::N5]
    } else {
        let j = i
            - N
            - crate::i18n_extra::N2
            - crate::i18n_extra2::N3
            - crate::i18n_extra3::N4
            - crate::i18n_extra4::N5
            - crate::i18n_extra5::N6;
        if j < crate::i18n_extra6::N7 {
            crate::i18n_extra6::EXTRA6[lang][j]
        } else if j < crate::i18n_extra6::N7 + crate::i18n_extra7::N8 {
            crate::i18n_extra7::EXTRA7[lang][j - crate::i18n_extra6::N7]
        } else if j < crate::i18n_extra6::N7 + crate::i18n_extra7::N8 + crate::i18n_extra8::N9 {
            crate::i18n_extra8::EXTRA8[lang][j - crate::i18n_extra6::N7 - crate::i18n_extra7::N8]
        } else if j < crate::i18n_extra6::N7 + crate::i18n_extra7::N8 + crate::i18n_extra8::N9 + crate::i18n_extra9::N10 {
            crate::i18n_extra9::EXTRA9[lang][j - crate::i18n_extra6::N7 - crate::i18n_extra7::N8 - crate::i18n_extra8::N9]
        } else {
            crate::i18n_extra10::EXTRA10[lang][j - crate::i18n_extra6::N7 - crate::i18n_extra7::N8 - crate::i18n_extra8::N9 - crate::i18n_extra9::N10]
        }
    }
}

/// True when the text is one of the built-in sample sentences (not something the person typed).
pub fn is_sample(text: &str) -> bool {
    LANGS.iter().any(|l| l.words[K::Pangram as usize] == text)
}

pub fn index_of(code: &str) -> usize {
    LANGS.iter().position(|l| l.code == code).unwrap_or(0)
}

